ويمكن توضيح دراسة العلاقة تقييم/تعلم بالارتباط مع **الأنواع الأربعة للتقييم** التي تُصادف عموماً في تدريس التربية البدنية والرياضية، وهي: التقييم **التشخيصي**، والتقييم **التكويني** (formative)، والتقييم **التكويني-الذاتي** (formatrice)، والتقييم **الإجمالي** (sommative).

