## الموضوع 2 — التقييم والتعلم في التربية البدنية (16 نقطة)

**نص السؤال (من الورقة):**

> «Montrez que l''évaluation et l''apprentissage en EPS sont intimement liés.»
>
> «Illustrez vos propos par des exemples pratiques pris dans des Activités Physiques et Sportives (APS) de votre choix.»

**الجواب — عناصر الإجابة الرسمية (المركز الوطني للتقويم والامتحانات)، في حدود الصفحات الموجودة في المسح:**

