## الموضوع 1 — السؤال 2أ (10 نقاط)

**نص السؤال (من الورقة):**

> «Elaborez une tâche d''apprentissage avec des variantes permettant de répondre de manière différenciée aux besoins des trois groupes. (10 points)»
>
> «NB : Dans l''élaboration de la tâche, il faut indiquer : l''objectif à atteindre, le schéma de l''organisation humaine et matérielle, les consignes d''exécution, les critères de réussite (1 quantitatif et 1 qualitatif) et les variables didactiques (évolution).»

**الجواب — عناصر الإجابة الرسمية (المركز الوطني للتقويم والامتحانات):**

مهمة التعلم التي يقترحها المرشح يجب أن تسمح بالاستجابة في آنٍ واحد لحاجات المجموعات الثلاث:

- **للمستوى الأول (المبتدئ):** يجب أن تركّز المهمة على بناء العلامات، وتعلم معايرة الانطلاق، وربط مرحلتي الانطلاق والنداء. ولا يمنع ذلك أن يعطي الأستاذ لهذه المجموعة بعض الإشارات حول التعليق والاستقبال.
- **للمستوى الثاني (المتمكّن):** يجب أن تركّز المهمة على تثبيت معايرة الانطلاق، مع البحث عن نسبة سعة/تردد مثالية لربط مثالي انطلاق–نداء. وسيبدأ الأستاذ أيضاً في التدخل (تعليمات وتغذية راجعة) على الجوانب التقنية المحددة لجودة التعليق والاستقبال.
- **للمستوى الثالث:** يجب أن تتمحور المهمة حول إتقان العناصر التقنية المحددة لجودة التعليق — دفع ركبة الرجل المُعادة (رجل النداء) نحو الأعلى والأمام، مدّ الجذع، الدور الموازِن للذراعين — والاستقبال — عمل متزامن لإسقاط الرجلين نحو الأمام، إغلاق الجذع، إعادة الذراعين الممدودتين نحو الأمام. وسينظر الأستاذ أيضاً في تمارين تستدعي صفتي القوة والسرعة لتحسين فعالية الانطلاق وانفجارية النداء. وينطبق الأمر نفسه على عمل المرونة لصالح سعة الحركات. واللجوء إلى تمارين التنسيق والتزامن مهم أيضاً للسماح بضبط الحركة وسلاستها. **غير أنه يُوصى بأن يذكر المرشحون أن استدعاء هذه الصفات وتطويرها يجب أن يُبحث عنه لدى جميع التلاميذ مهما كان مستواهم.**

ولكي تكون مهمة التعلم ذات جودة، يجب أن:

- تكون **ملائمة** للهدف والصعوبات التي تدّعي حلها، أو الصفات المراد تطويرها؛
- تقدّم **تنظيماً مكانياً ومادياً مثالياً** لضمان عدد كافٍ من التكرارات (الانخراط الحركي). وسيكون من الجيد أن يقترح المرشحون مهمة موزعة على **ورشتين تستغلان الحفرة طولاً**:
  - واحدة للمستوى الأول تركّز على بناء العلامات، وتعلم معايرة الانطلاق، وربط مرحلتي الانطلاق والنداء؛
  - وواحدة للمستويين الثاني والثالث تركّز على تثبيت وصقل الربط بين مرحلتي الانطلاق والنداء، ويجب فيها وضع تهيئة مادية (مطاط، حصيرة سقوط) تستدعي المهارات التقنية المفضية إلى جودة التعليق والاستقبال؛
- تأخذ في الاعتبار مشاكل **عدم تجانس المستويات والاختلاط** (mixité)؛
- تبيّن **كيف يمكن استغلال التلاميذ الأربعة المؤكدين**.

**تعليل/ملاحظة:** التصحيح الرسمي لا يفرض مهمة واحدة بعينها: يحدد ما يجب أن تسمح به المهمة، مستوىً بمستوى، ثم معايير الجودة الأربعة. اقتراح الورشتين اللتين تستغلان الحفرة نفسها مقدَّم صراحةً على أنه التنظيم المنتظر.

**مثال تطبيقي لمهمة كاملة (اقتراح مناصب — للاستئناس، يستوفي العناصر المطلوبة في الملاحظة NB):**

- **الهدف:** ربط انطلاق متسارع ونداء في منطقة نداء دون تباطؤ، لتحسين الأداء.
- **التنظيم البشري والمادي:** 3 ممرات انطلاق تنتهي إلى الحفرة، ممر لكل مجموعة؛ العمل في ثنائيات (واثب / ملاحظ–حكم) ثم التناوب؛ منطقة نداء مميزة بالجير: عرض 1م (المجموعة 1)، 60 سم (المجموعة 2)، 30 سم ثم اللوحة (المجموعة 3)؛ علامات انطلاق على الأرض؛ مطاط مشدود فوق الحفرة لحثّ المجموعة 3 على الارتفاع؛ حصيرة سقوط للتمارين التعليمية.
- **تعليمات التنفيذ:** الانطلاق من علامتك، التسارع تدريجياً، النظر إلى الأمام لا إلى اللوحة، أخذ النداء برجل واحدة في المنطقة دون دوس، رفع الركبة الحرة والذراعين، الاستقبال على الرجلين إلى الأمام.
- **معايير النجاح:** كمي — 3 نداءات من 4 داخل المنطقة + تحسن في الأداء (مثال: +20 سم مقارنة بالاختبار)؛ كيفي — لا دوس ولا تباطؤ قبل النداء (يحكم عليه الملاحظ).
- **المتغيرات الديداكتيكية:** عرض منطقة النداء (تضييقها تدريجياً)؛ طول الانطلاق (من 6–8 خطوات إلى انطلاق كامل)؛ ارتفاع المطاط؛ عدد الخطوات المفروض؛ وجود علامات وسيطة أو غيابها.
- **المتغيرات حسب المجموعة:** المجموعة 1: انطلاق مختصر (6 خطوات)، منطقة واسعة، تمارين تعليمية للخطوات الواثبة؛ المجموعة 2: انطلاق متوسط (10–12 خطوة)، منطقة 60 سم، عمل على إيقاع الخطوات الأخيرة؛ المجموعة 3: انطلاق كامل، اللوحة، مطاط للتعليق، عمل على الاستقبال.

