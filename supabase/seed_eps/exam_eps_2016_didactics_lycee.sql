## الموضوع 1 — السؤال 2ب (7 نقاط)

**نص السؤال (من الورقة):**

> «Justifiez l''intérêt des formes d''organisation pédagogique et des modes d''intervention que vous avez choisis dans la conduite et la gestion de la tâche d''apprentissage. (7 points)»

**الجواب — عناصر الإجابة الرسمية (المركز الوطني للتقويم والامتحانات):**

يجب على المرشح أن يبرّر فائدة أشكال التنظيم وطرق التدخل التي اختار استخدامها في قيادة مهمة التعلم وتنظيمها.

**كيف ولماذا كوّن مجموعات العمل** — فقط حسب المستوى، أو غير متجانسة، أو مختلطة. من حيث المبدأ، وبالنظر إلى حصيلة اختبار الملاحظة، يجب على المرشح أن يقترح تنظيم القسم في **مجموعتين من المستوى تضم كل منهما إناثاً وذكوراً**، وهو تنظيم يشجع الاختلاط (mixité). وسيكون من الجيد أن يُدمج التلاميذ الأربعة الأفضل في المجموعتين، **2 في كل مجموعة**، ليكونوا نموذجاً للآخرين (بيداغوجيا النموذج)، ولكي لا تُخلق مشاعر نقص أو إقصاء لدى الأضعف.

**لماذا نوع البيداغوجيا المستعملة:**

- **بيداغوجيا النموذج** يمكن استعمالها ما دام هناك 4 تلاميذ موارد يمكنهم تقديم عروض صحيحة في المجمل.
- **البيداغوجيا المفرّقة** يجب أن تبرز بالضرورة كخيار ذي أولوية، سواء في تشكيل المجموعات أو في تنظيم أداء التلاميذ. فتلاميذ كل مجموعة مستوى لهم حاجات خاصة تتطلب تعلمات وتصحيحات وتعزيزات محددة: المجموعة الأولى تحتاج إلى التعلم والتنظيم فيما يخص معايرة الانطلاق وربط مرحلتي الانطلاق والنداء؛ والمجموعة الثانية تحتاج إلى التعلم والتنظيم فيما يخص تثبيت وصقل الربط بين مرحلتي الانطلاق والنداء؛ والتلاميذ الأربعة الجيدون، الموزعون على المجموعتين، يحتاجون إلى التعلم والتنظيم فيما يخص استدعاء المهارات التقنية المفضية إلى جودة التعليق والاستقبال.
- من البديهي أن قيادة التعلمات وتدبيرها يجب ألا تُغفل **تثمين إنتاج الأداءات**، احتراماً لمنطق الوثب الطويل بوصفه نشاطاً رياضياً. *(النص الرسمي يقول «saut en hauteur» — خطأ مطبعي في الوثيقة المصدر، انظر الملاحظة 5.)*
- **بيداغوجيا العقد** يمكن أن يقترحها المرشح، لا سيما فيما يخص تحديد التلاميذ لأهداف تتمحور حول تحسين أداءاتهم، في نهاية الدورة وليس في الإطار الضيق لمهمة التعلم التي هي مجرد مرحلة. وهذا يسمح بإعطاء معنى للمهارات التقنية المراد بناؤها بالنسبة إلى الأداء الذي تسهم فيه إلى حد كبير.
- **تثمين تنمية الكفاءات العامة لدى التلاميذ**، المشار إليها في الجدول المرجعي المأخوذ من التوجهات البيداغوجية، والمتعلقة بالجوانب المرتبطة بالمعارف السلوكية والمفاهيمية، عبر الملاحظة المشتركة (co-observation)، والتغذية الراجعة بين التلاميذ، وتقاسم المسؤوليات، وأخذ القياسات.

**تبرير إضافي مقترح (اقتراح مناصب — للاستئناس، متوافق مع الرسمي):**

- **مجموعات الحاجة:** البيداغوجيا المفرّقة تسمح لكل تلميذ بالتقدم حسب مستواه؛ وتتجنب فشل المجموعة الضعيفة وملل المجموعة القوية.
- **العمل في ثنائيات بأدوار (حكم، ملاحظ):** تحميل المسؤولية، والكفاءات المنهجية والاجتماعية (وحدات التوجهات البيداغوجية)، والتغذية الراجعة بين الأقران.
- **ورشات متزامنة:** زمن انخراط حركي مرتفع، وانتظار أقل.
- **طرق التدخل:** العرض والتعليمات القصيرة في البداية؛ ثم التوجيه بالتغذية الراجعة (وصفية، توجيهية، استجوابية)؛ الأستاذ يتنقل في المقام الأول نحو المجموعة 1؛ وضع التلاميذ موضع تفكير («لماذا عضضتَ؟») لتنمية الاستقلالية؛ السلامة (حفرة ممهدة، ممرات خالية).

