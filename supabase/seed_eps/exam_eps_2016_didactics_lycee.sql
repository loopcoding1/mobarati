## الموضوع 2 — التقييم والتعلم في التربية البدنية (16 نقطة)

**نص السؤال (من الورقة):**

> «Montrez que l''évaluation et l''apprentissage en EPS sont intimement liés.»
>
> «Illustrez vos propos par des exemples pratiques pris dans des Activités Physiques et Sportives (APS) de votre choix.»

**الجواب — عناصر الإجابة الرسمية (المركز الوطني للتقويم والامتحانات)، في حدود الصفحات الموجودة في المسح:**

صياغة الموضوع تدعو المرشحين إلى إظهار أن التقييم والتعلمات في التربية البدنية والرياضية مرتبطة ارتباطاً وثيقاً. ويجب أن يكون إثبات صحة هذه العلاقة مصحوباً بتوضيحات تطبيقية في أنشطة بدنية ورياضية مختلفة. ويجب على المرشحين فعلاً أن يُظهروا أنهم يتوفرون على معارف نظرية وقدرات على التحليل والإثبات، مع القدرة على إقامة العلاقة بوضوح بين ما هو نظري وما هو من ممارسة التعليم–التعلم في إطار التربية البدنية والرياضية.

ويمكن توضيح دراسة العلاقة تقييم/تعلم بالارتباط مع **الأنواع الأربعة للتقييم** التي تُصادف عموماً في تدريس التربية البدنية والرياضية، وهي: التقييم **التشخيصي**، والتقييم **التكويني** (formative)، والتقييم **التكويني-الذاتي** (formatrice)، والتقييم **الإجمالي** (sommative).

**العلاقة بين التقييم التشخيصي والتعلم.** أثناء هذا التقييم، يجمع الأستاذ عدداً من المعطيات حول خصائص التلاميذ (المستوى، المواقف)، قصد تخطيط مشروع دورة يحدد أهداف التعلم ومحتويات التدريس الملائمة، وتوزيع التلاميذ في مجموعات مستوى مع أخذ فكرة عن مواقفهم. وبدون استغلال حكيم للتقييم التشخيصي، لن يكون لتخطيط التعلمات أي وجاهة، وقد لا يستجيب للحاجات الخاصة بمجموعة القسم، ومن ثم يعرض للخطر حسن قيادة وتنظيم مسار التعليم–التعلم.

أمثلة: في **سباق الحواجز**، يكون تخطيط أهداف تعلم تتمحور حول تجاوز الحاجز غير ملائم وغير مناسب إذا أظهر التلاميذ في اختبار الملاحظة مشاكل في الإمساك بالحاجز والهجوم عليه. وفي **كرة اليد**، إذا لاحظ الأستاذ أثناء اختبار الملاحظة صعوبات في الحفاظ على الكرة لبناء هجوم متمركز، سيكون من الأنسب أن يحدد أهدافاً وأن يقترح وضعيات تعلم تتمحور حول تدرج اللعب واتساعه والنداءات في الفضاءات الحرة في العمق، بدل التركيز على تعلم التثبيت–الإزاحة (fixation-décalage).

**العلاقة بين التقييم التكويني والتعلم.** أثناء الدورة، يُجرى التقييم التكويني من طرف الأستاذ بالرجوع إلى معايير دقيقة قد تكون مُصاغة أو لا. ويسمح هذا التقييم بتحديد تقدم التلاميذ ورصد الصعوبات التي يواجهونها في مسار التعلم. وتبعاً للملاحظات... **[ينقطع النص الرسمي هنا: الصفحة 4 من 5 من التصحيح مفقودة من الملف المصدر، فلا تُستنسخ التطويرات حول التقييم التكويني والتقييم التكويني-الذاتي والتقييم الإجمالي].**

**شبكة تقييم الإنتاج الكتابي للموضوع الثاني، كما هي منقولة في الصفحة الأخيرة من التصحيح الرسمي:**

| المجال | النقط | المعايير |
|---|---|---|
| المعارف (Connaissances) | 4 | استحضار المعارف، ملاءمة المعارف للموضوع، غنى المعارف، معارف مرجعية |
| الحجاج (Argumentation) | 6 | منطق وتماسك الإثبات، هيكلة الحجج ونمذجتها |
| العلاقة نظرية/تطبيق (Rapport théorie–pratique) | 6 | تنوع الأمثلة، ملاءمة الأمثلة، قابلية التوضيحات للتطبيق |
| **المجموع** | **16** | |

**تعليل/ملاحظة:** الشبكة الرسمية تقول أكثر من التصحيح نفسه: 6 نقط من 16 تخص العلاقة نظرية/تطبيق، أي الأمثلة، و6 تخص الحجاج. فمقال يكتفي بتعريف الأنواع الأربعة للتقييم، دون توضيحها في أنشطة بدنية ورياضية متنوعة، لا يتجاوز ربع النقطة تقريباً.

**تكملة الخطة — اقتراح مناصب (خطة مفصلة، للاستئناس وليست نصاً رسمياً):**

- **الإشكالية:** بأي معنى يكون التقييم، بعيداً عن كونه مجرد عقوبة نهائية، جزءاً لا يتجزأ من مسار التعلم في التربية البدنية والرياضية؟
- **أولاً — التقييم يوجّه التعلم:** التقييم التشخيصي (اختبار ملاحظة، وضعية مرجع)؛ يسمح برصد المستويات، وتشكيل مجموعات الحاجة، وتحديد الأهداف. مثال: اختبار السرعة الهوائية القصوى (VMA) في سباق المداومة، وضعية مرجع في الوثب الطويل.
- **ثانياً — التقييم ينظّم التعلم:** التقييم التكويني والتكويني-الذاتي (معايير نجاح وإنجاز يعرفها التلميذ، بطاقات ملاحظة، التقييم المشترك والتقييم الذاتي، التغذية الراجعة). مثال: في **الكرة الطائرة**، بطاقة ملاحظة للإرسالات الناجحة؛ في **الجمباز**، التقييم الذاتي للتسلسل انطلاقاً من فيديو.
- **ثالثاً — التقييم يشهد وينعش التعلم:** التقييم الإجمالي في نهاية الوحدة (الأداء، إتقان التنفيذ، المعارف، المواقف، وفق التوجهات البيداغوجية)؛ ويُستعمل أيضاً كحصيلة لمشروع جديد. الحدود: خطر النقطة–العقوبة والإحباط، ومن هنا أهمية تثمين التقدم.
- **خاتمة:** التقييم هو التعلم؛ والتقييم المندمج يجعل التلميذ فاعلاً ويعطي معنى للتعلمات.

